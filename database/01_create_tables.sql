-- 1. ROOMS TABLE
CREATE TABLE IF NOT EXISTS public.rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    room_type VARCHAR(20) NOT NULL
        CHECK (room_type IN ('Single', 'Double', 'Deluxe', 'Suite')),
    price_per_night NUMERIC(10,2) NOT NULL
        CHECK (price_per_night > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Occupied')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. BOOKINGS TABLE
CREATE TABLE IF NOT EXISTS public.bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    room_id BIGINT NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    amount NUMERIC(10,2) NOT NULL
        CHECK (amount > 0),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (payment_status IN ('Paid', 'Pending')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_booking_room
        FOREIGN KEY (room_id)
        REFERENCES public.rooms(room_id)
        ON DELETE RESTRICT,

    CONSTRAINT valid_booking_dates
        CHECK (check_out > check_in)
);

-- 3. EXPENSES TABLE
CREATE TABLE IF NOT EXISTS public.expenses (
    expense_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_name VARCHAR(100) NOT NULL,
    expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
    amount NUMERIC(10,2) NOT NULL
        CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. CREATE INDEXES
CREATE INDEX IF NOT EXISTS idx_bookings_room_id
ON public.bookings(room_id);

CREATE INDEX IF NOT EXISTS idx_bookings_check_in
ON public.bookings(check_in);

CREATE INDEX IF NOT EXISTS idx_bookings_payment_status
ON public.bookings(payment_status);

CREATE INDEX IF NOT EXISTS idx_expenses_date
ON public.expenses(expense_date);

-- 5. ENABLE ROW LEVEL SECURITY
ALTER TABLE public.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;

